int j2v_theme_serial;

uint32_t theme_color(int slot) {
    int t = j2v_global.theme;
    if (t < 0 || t >= THEME_COUNT)
        t = 0;
    if (slot < 0 || slot >= TC_COUNT)
        return 0;
    return themes[t][slot];
}
